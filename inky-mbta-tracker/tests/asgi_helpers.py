from urllib.parse import urlencode

from fastapi import FastAPI, Response
from starlette.types import Message


async def get_response(
    app: FastAPI, path: str, params: dict[str, str] | None = None
) -> Response:
    """Exercise the ASGI app without starting network clients or a test server."""
    messages: list[Message] = []

    async def receive() -> Message:
        return {"type": "http.request", "body": b"", "more_body": False}

    async def send(message: Message) -> None:
        messages.append(message)

    await app(
        {
            "type": "http",
            "asgi": {"version": "3.0", "spec_version": "2.4"},
            "http_version": "1.1",
            "method": "GET",
            "scheme": "http",
            "path": path,
            "raw_path": path.encode(),
            "query_string": urlencode(params or {}).encode(),
            "headers": [],
            "client": ("127.0.0.1", 1234),
            "server": ("testserver", 80),
        },
        receive,
        send,
    )
    start = next(m for m in messages if m["type"] == "http.response.start")
    body = b"".join(
        m.get("body", b"") for m in messages if m["type"] == "http.response.body"
    )
    response = Response(content=body, status_code=start["status"])
    response.raw_headers = start["headers"]
    return response
